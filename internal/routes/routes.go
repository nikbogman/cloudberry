package routes

import (
	"encoding/json"
	"fmt"
	"net/url"
	"os"
	"regexp"
	"strings"
)

// Route is one stack exposed through the Router, at its own tsnet hostname
// https://<Name>.<tailnet>.ts.net, unless Path is set.
type Route struct {
	Name string `json:"name"`
	// Port is the loopback listen port; only path routes use it.
	Port int `json:"port,omitempty"`
	// Path publishes the route under this prefix on 443, beside /wake, instead
	// of on its own port. `tailscale serve` strips the prefix before proxying.
	Path     string `json:"path,omitempty"`
	Upstream string `json:"upstream"`
	// Public routes go on Funnel; the rest are tailnet-only.
	Public bool `json:"public"`
	// Wake routes wake blackberry on request; the rest 502 while it's asleep.
	Wake bool `json:"wake"`
	// IdleMinutes overrides the file's idle_minutes for this route: shorter
	// for stacks that never touch the HDD, so a spin-up isn't kept running
	// for nothing. Filled from the default by Load.
	IdleMinutes int `json:"idle_minutes,omitempty"`
}

// Routes is the routes file, generated by cmd/routes from the stacks repo.
type Routes struct {
	IdleMinutes int     `json:"idle_minutes"`
	Routes      []Route `json:"routes"`
}

var hostLabel = regexp.MustCompile(`^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$`)

func Load(path string) (Routes, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return Routes{}, err
	}
	return Parse(data, path)
}

// Parse validates a routes file and fills each route's default
// idle_minutes. path only labels errors.
func Parse(data []byte, path string) (Routes, error) {
	var cfg Routes
	if err := json.Unmarshal(data, &cfg); err != nil {
		return cfg, fmt.Errorf("%s: %w", path, err)
	}
	if cfg.IdleMinutes <= 0 {
		return cfg, fmt.Errorf("%s: idle_minutes must be positive", path)
	}
	seen := map[int]bool{}
	seenName := map[string]bool{}
	seenPath := map[string]bool{}
	for i, r := range cfg.Routes {
		if r.IdleMinutes < 0 {
			return cfg, fmt.Errorf("%s: route %q: idle_minutes must be positive", path, r.Name)
		}
		if r.IdleMinutes == 0 {
			cfg.Routes[i].IdleMinutes = cfg.IdleMinutes
		}
		if !hostLabel.MatchString(r.Name) {
			return cfg, fmt.Errorf("%s: route %q: name must be a lowercase DNS label (a-z, 0-9, -)", path, r.Name)
		}
		if seenName[r.Name] {
			return cfg, fmt.Errorf("%s: name %q used twice", path, r.Name)
		}
		seenName[r.Name] = true
		if r.Path != "" {
			if r.Port == 443 {
				return cfg, fmt.Errorf("%s: route %q: port 443 is the gateway's own tailscale serve, for /wake", path, r.Name)
			}
			if r.Port <= 0 || seen[r.Port] {
				return cfg, fmt.Errorf("%s: route %q: path routes need a unique loopback port", path, r.Name)
			}
			seen[r.Port] = true
		}
		if u, err := url.Parse(r.Upstream); err != nil || u.Scheme == "" || u.Host == "" {
			return cfg, fmt.Errorf("%s: route %q: upstream must be an absolute URL", path, r.Name)
		}
		if r.Path != "" {
			if !strings.HasPrefix(r.Path, "/") || r.Path == "/" || strings.HasSuffix(r.Path, "/") {
				return cfg, fmt.Errorf("%s: route %q: path must look like /name; / is /wake's", path, r.Name)
			}
			// Funnel is per port: turning it on for 443 would make /wake public too.
			if r.Public {
				return cfg, fmt.Errorf("%s: route %q: a path route can't be public", path, r.Name)
			}
			if seenPath[r.Path] {
				return cfg, fmt.Errorf("%s: path %s used twice", path, r.Path)
			}
			seenPath[r.Path] = true
		}
	}
	return cfg, nil
}
